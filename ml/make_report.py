"""docs/task5_report.md, built only from ml/results.json and backend/app/ai/model.json.

Filled in Task 5 phase 6. A report someone could hand-edit is a report that drifts from the run
that produced it, so every figure here is read out of the files the scripts wrote.

Three numbers are read out of the backend source instead, because they are rules a human chose and a
JSON file would make them sound like measurements: the capacity the relocation rules assume, the age
at which a node stops counting as online, and the two thresholds the risk bands use. Each is looked up
by name and the script stops if it cannot find it, so a rename shows up here as an error rather than as
a stale figure in a document nobody re-checks.

Run with the ml virtual environment, from the repository root:

    ml/.venv/Scripts/python.exe ml/make_report.py
"""
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "ml" / "results.json"
MODEL = ROOT / "backend" / "app" / "ai" / "model.json"
OUT = ROOT / "docs" / "task5_report.md"
RELOCATION = ROOT / "backend" / "app" / "ai" / "relocation.py"
MAIN = ROOT / "backend" / "app" / "main.py"
PREDICT = ROOT / "backend" / "app" / "ai" / "predict.py"
FEATURES = ROOT / "backend" / "app" / "ai" / "features.py"


def load(path):
    if not path.exists():
        raise SystemExit(f"{path.relative_to(ROOT)} is missing - run ml/generate_data.py, ml/train.py and "
                         f"ml/evaluate.py first; the report has nothing to quote without them.")
    return json.loads(path.read_text(encoding="utf-8"))


def const(path, name):
    """A module-level `NAME = <literal>` read out of a source file.

    Parsed rather than imported: this runs in the ml venv, which has no FastAPI, and a backend that
    cannot be imported would make a worse report generator than one that reads the text.
    """
    for node in ast.parse(path.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise SystemExit(f"{name} is no longer a module-level literal in {path.name}; the report would be wrong.")


def capacity_default():
    """The number read_capacity() falls back to when MAX_BATCHES_PER_FRIDGE is unset."""
    found = re.search(r"if not raw:\s*\n\s*return (\d+)", MAIN.read_text(encoding="utf-8"))
    if not found:
        raise SystemExit("read_capacity()'s fallback is not the shape make_report.py expects.")
    return int(found.group(1))


def table(header, rows):
    return [f"| {' | '.join(header)} |", "|" + "|".join(["---"] * len(header)) + "|",
            *["| " + " | ".join(str(c) for c in row) + " |" for row in rows]]


def main():
    res, model = load(RESULTS), load(MODEL)
    data, split, reg, breach, episodes = (res["data"], res["split"], res["regression_on_test"],
                                          res["breach_on_test"], res["episodes_on_test"])
    health, walk = res["compressor_health"], res["stdlib_walk_check"]
    selection, model_meta = model["selection"], res["model"]
    temp30, max30 = reg["temp30"], reg["max30"]
    overall, weak = episodes["overall"], health["per_scenario"]["weak_compressor"]
    ttl, weak_score = const(RELOCATION, "SUGGESTION_TTL_S"), const(RELOCATION, "WEAK_SCORE")
    watch_margin = const(PREDICT, "RISK_WATCH_MARGIN_C")
    hysteresis = const(FEATURES, "HYSTERESIS_C")
    online_age, capacity = const(MAIN, "ONLINE_AGE_S"), capacity_default()

    out = ["# Task 5 - AI breach prediction and relocation", "",
           f"Generated by `ml/make_report.py` from `ml/results.json` (written {res['generated_at']}) and "
           f"`backend/app/ai/model.json` (written {model['generated_at']}). Nothing in it was typed by hand: "
           "change the run, not the document.", "",
           f"> `ml/results.json`: {data['source']}",
           f"> `backend/app/ai/model.json`: {model['data']}", "",
           "## Problem", "",
           "The backend could already tell an operator that a fridge was above 8 °C. That answer arrives after "
           "the vaccine inside has started spending its heat budget, which is the wrong moment to learn anything. "
           f"Task 5 reads the same stored rows three more ways: a forecast of the next {model['horizon_min']} "
           "minutes, a 0-100 compressor health score that is meant to drift before the temperature does, and a "
           "relocation plan that turns the two into one move an operator can confirm. Every number is served by a "
           "route and printed with the figures it came from - there is no score the page can show but the "
           "backend cannot explain.", "",
           "## Dataset", "",
           f"{data['streams']} streams over {len(data['scenarios'])} scenarios ({', '.join(data['scenarios'])}) = "
           f"{data['windows']:,} one-minute windows, from `ml/generate_data.py --seed {model['seed']}`. Each stream "
           "is a fridge with a duty cycle, a room temperature, a compressor that cools in steps and faults "
           f"injected at fixed minutes. Split oldest-to-newest inside each stream: {split['train']:,} train, "
           f"{model['split']['val']:,} validation and {split['test']:,} test windows, with a "
           f"{split['purge_min']}-minute purge around the {len(split['walls_at_epoch_minute'])} time walls "
           f"({split['purged_rows_at_walls']} rows dropped) so a feature that looks backwards cannot reach into "
           "the window it is being scored on.", "",
           "## Features", "",
           f"{len(model['feature_names'])} numbers per window, computed by `backend/app/ai/features.py` - the same "
           "file the running server imports, so a feature cannot be built one way at training and another way in "
           "service: " + ", ".join(f"`{f}`" for f in model["feature_names"]) + ". "
           f"They need {model['min_history_min']} contiguous minutes before any of them exists, which is why a "
           "fridge that has just been plugged in is refused instead of guessed at. The compressor-derived features "
           "(`duty_15`, `door_min_15`, `power_off_min_15`) are the same signals the health score reads, and "
           "`flags_known` tells the model when a node does not report those pins at all.", "",
           "## Models and baselines", "",
           "Two heads: " + "; ".join(
               f"`{k}` = {model_meta['heads'][k]} ({p['n_estimators']} depth-{p['max_depth']} trees, "
               f"learning rate {p['learning_rate']}, subsample {p['subsample']})"
               for k, p in ((k, selection[k]["gbm_params"]) for k in selection)) +
           f". Both were fitted in {model['fit_seconds']} s into {model_meta['bytes']:,} bytes of JSON that the "
           "standard library walks at request time, which is why `backend/requirements.txt` gained nothing: the "
           "training libraries live in `ml/.venv` and neither the backend nor Render ever sees them.", "",
           "Three things it is measured against:"]
    out += table(["baseline", "temp30 RMSE °C", "max30 RMSE °C", "which windows"],
                 [("ridge on the same scaled features (the reference the choice was made against)",
                   selection["temp30"]["ridge"][str(selection["temp30"]["ridge_reference"]["alpha"])],
                   selection["max30"]["ridge"][str(selection["max30"]["ridge_reference"]["alpha"])], "validation"),
                  ("this model (gbm)", selection["temp30"]["gbm_val_rmse"], selection["max30"]["gbm_val_rmse"], "validation"),
                  ("this model (gbm)", selection["temp30"]["gbm_test_rmse"], selection["max30"]["gbm_test_rmse"],
                   f"test ({max30['n']:,})"),
                  ("fallback: straight line from the last minutes, no model at all",
                   reg["fallback_temp30"]["rmse_c"], reg["fallback_max30"]["rmse_c"], "test")])
    out += ["",
            "The ridge row is the sweep's validation number, because that is the only ridge figure "
            "`results.json` keeps - the head was chosen on it and gbm won, so its test score was never recorded. "
            "The fallback is what the backend answers when `model.json` is absent, scored on exactly the same "
            f"{max30['n']:,} test windows - worth putting in writing, because \"the model is decent\" and \"the "
            "model beats nothing\" are different claims.", "",
            "## Results", "", "### Temperature on the held-out windows", ""]
    out += table(["prediction", "MAE °C", "RMSE °C", "bias °C", "windows", "same, with no model (MAE °C)"],
                 [("temp30 - temperature 30 min ahead", temp30["mae_c"], temp30["rmse_c"], temp30["bias_c"],
                   f"{temp30['n']:,}", reg["fallback_temp30"]["mae_c"]),
                  ("max30 - peak over the next 30 min", max30["mae_c"], max30["rmse_c"], max30["bias_c"],
                   f"{max30['n']:,}", reg["fallback_max30"]["mae_c"])])
    out += ["",
            "The alarm is raised on `max30`, because a cold chain is ruined by the worst minute ahead rather than "
            f"the last one: precision {breach['precision']:.1%} ({breach['tp']} true against {breach['fp']} false "
            f"minutes), recall {breach['recall']:.1%} ({breach['fn']} breach-minutes missed), F1 {breach['f1']}. "
            f"Per fridge-day of test data the model gives {breach['false_alarms_per_fridge_day']} false alarms; the "
            f"fallback gives {breach['fallback']['fp'] / breach['fridge_days_in_test']:.1f} "
            f"({breach['fallback']['fp']} in {breach['fridge_days_in_test']} fridge-days). Those counts weigh one minute "
            "sample at a time, so a nine-minute breach is nine positives; this is the same test set counted once "
            "per event:", ""]
    out += table(["scenario", "episodes", "detected", "missed", "alarmed before the line", "mean lead min",
                  "shortest lead min", "mean length min"],
                 [(name, e["episodes"], e["detected"], e["missed"], e["alarmed_early"], e["mean_lead_min"],
                   e["min_lead_min"], e["mean_length_min"])
                  for name, e in episodes.items() if name != "overall"])
    out += ["",
            f"Overall {overall['detected']}/{overall['episodes']} episodes detected, {overall['alarmed_early']} of "
            f"them while the fridge was still under the threshold, mean lead {overall['mean_lead_min']} min. "
            "`normal` and `weak_compressor` hold no episodes by construction - the generator never drives them "
            "over 8 °C - so for those two the only thing measured is how often the model cries wolf.", "",
            "### Compressor health", "",
            f"{health['method'].rstrip('.')}. It is not a fitted model: it has no held-out wear and no accuracy to "
            "quote. What is measured is direction and collateral damage.", ""]
    out += table(["check", "expected", "measured"], [(c["check"], c["expected"], c["measured"]) for c in health["checks"]])
    out += ["",
            f"On the stream whose pull is deliberately decayed, the score runs {weak['start_score']} → "
            f"{weak['end_score']} with {weak['points_in_weak_band']} of {weak['rolling_points']} points below "
            f"{weak_score}; on the streams given no fault it never enters that band "
            f"({health['per_scenario']['normal']['points_in_weak_band']} of "
            f"{health['per_scenario']['normal']['rolling_points']} points). The page shows the number with its "
            "reason lines, so an operator can disagree with it.", "",
            "### The served code against the library that trained it", ""]
    out += table(["head", "windows walked", "largest stdlib minus sklearn gap °C",
                  f"windows over {walk[0]['tolerance_c']} °C", "test RMSE gap °C"],
                 [(w["head"], f"{w['windows']:,}", w["max_abs_diff_c"],
                   f"{w['windows_over_tolerance']} ({w['share_over_tolerance']:.4%})", w["rmse_gap_c"]) for w in walk])
    out += ["",
            "Every metric above comes from the standard-library walk - the code that actually runs in the backend - "
            "not from sklearn predicting on its own objects. sklearn walks its trees in float32, so a few windows "
            "per head take the other branch at a split; `evaluate.py` fails the run if that disagreement grows.", "",
            "## How relocation decides", "",
            "`GET /api/ai/relocations` forecasts every fridge (with `episode=False`, so two operators refreshing "
            "the page cannot spend the one breach warning a heat wave is allowed to raise) and then applies plain "
            f"rules. A fridge is at risk when it is reporting over {split['threshold_c']:g} °C now or its forecast "
            f"peak crosses that line. A destination must be online within {online_age} s, on mains, door shut, "
            f"forecast risk not high, health score at least {weak_score} and one place free, where a fridge is "
            f"assumed to hold {capacity} batches unless `MAX_BATCHES_PER_FRIDGE` says otherwise. Batches are offered "
            "in order of remaining budget minutes, destinations ranked by temperature then health, and a free place "
            "is spent as it is promised, so two batches are never told the same slot is theirs. A suggestion id hashes batch, source, "
            f"destination and the current {ttl // 60}-minute window, so the page cannot confirm a stale plan.", "",
            "`POST /api/ai/relocations/confirm` - pharmacist or admin only - recomputes the plan on the server, "
            "answers 409 with the reason the move is no longer there if it is not, and otherwise performs it "
            "through the same batch-move code the Inventory page already uses, writes a `RELOCATION_CONFIRMED` row "
            "into the audit chain; a second click on the same suggestion is answered from that row rather than by "
            "moving the batch again. The "
            "temperature, budget minutes, free places and blockers on the card are the ones the decision used.", "",
            f"The `watch` band begins {watch_margin:g} °C below the threshold, which is about one model error: the "
            f"peak head measures {max30['mae_c']} °C MAE on the test windows. A fridge predicted to stop within "
            "one error of the line is worth a look rather than reported as safe. Separately, a heat episode must "
            f"fall {hysteresis:g} °C under the line before a new episode is counted, so one long warm afternoon "
            "arrives as one warning rather than as five.", "",
            "## Limitations", ""]
    out += [f"- {h}" for h in res["honesty"]]
    out += ["",
            f"- a node that reports less often than every {online_age} s reads as offline, so it can never be a "
            "destination: on a fleet that phones home once a minute the plan says \"nowhere to go\" correctly and "
            "permanently. That threshold is a site decision, and it is the first thing to check when the panel "
            "looks empty.",
            f"- {capacity} batches per fridge is declared, not measured. Nothing in the database knows the size of "
            "a fridge, so the capacity the rules protect is one number a person has to get right.",
            "- the forecast has never met a real door seal, defrost cycle or ward power cut. These numbers describe "
            "the pipeline, and the pipeline is the only thing being claimed.",
            "- relocation is deterministic: same readings, same suggestion. It cannot learn that a particular ward "
            "always recovers on its own, and it should not try to before somebody has watched it.", "",
            "## How to reproduce", "",
            "```powershell",
            "python -m venv ml/.venv",
            "ml/.venv/Scripts/python.exe -m pip install -r ml/requirements-ml.txt",
            f"ml/.venv/Scripts/python.exe ml/generate_data.py --seed {model['seed']}",
            "ml/.venv/Scripts/python.exe ml/train.py",
            "ml/.venv/Scripts/python.exe ml/evaluate.py",
            "ml/.venv/Scripts/python.exe ml/make_report.py",
            "```", "",
            "The backend needs none of it: `cd backend && venv\\Scripts\\python.exe -m pytest -q` tests the served "
            "model against fixtures, and `cd frontend && npm run build` builds the Insights page that reads those "
            "routes. `train.py` runs on the committed `ml/data/sample.csv` alone but says loudly that it is too "
            f"small - regenerate first. Seed {model['seed']} reproduces every figure here; a different seed moves "
            "them, which is why the seed is printed rather than remembered.", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(out).replace("\r\n", "\n") + "\n"
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}: {len(text.splitlines())} lines, {len(text)} characters")
    print(f"headline: max30 MAE {max30['mae_c']} C | precision {breach['precision']} recall {breach['recall']} "
          f"| episodes {overall['detected']}/{overall['episodes']} mean lead {overall['mean_lead_min']} min "
          f"| weak stream score {weak['start_score']}->{weak['end_score']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
